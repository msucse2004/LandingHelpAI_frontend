/**
 * @param {string | null | undefined} lang
 * @returns {Record<string, string>}
 */
export function getLocalizationLocaleBundle(lang) {
  const code = normalizeSupportedLanguageCode(lang) || DEFAULT_LANGUAGE_CODE;
  const base = LOCALIZATION_LOCALES.en || {};
  const locale = LOCALIZATION_LOCALES[code] || {};
  return { ...base, ...locale };
}

/**
 * @param {string | null | undefined} lang
 */
export function overlayLocalizationLocaleForLanguage(lang) {
  overlayI18nStrings(getLocalizationLocaleBundle(lang));
}
