/**
 * @param {string | null | undefined} lang
 * @returns {Record<string, string>}
 */
export function getAuthPublicLocaleBundle(lang) {
  const code = normalizeSupportedLanguageCode(lang) || DEFAULT_LANGUAGE_CODE;
  const base = AUTH_PUBLIC_LOCALES.en || {};
  const locale = AUTH_PUBLIC_LOCALES[code] || {};
  return { ...base, ...locale };
}

/**
 * Force auth (+ common loading) strings for the active UI language after API reload.
 * @param {string | null | undefined} lang
 */
export function overlayAuthPublicLocaleForLanguage(lang) {
  overlayI18nStrings(getAuthPublicLocaleBundle(lang));
}
