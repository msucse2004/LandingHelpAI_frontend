/**
 * @param {string | null | undefined} lang
 * @returns {Record<string, string>}
 */
export function getAppShellLocaleBundle(lang) {
  const code = normalizeSupportedLanguageCode(lang) || DEFAULT_LANGUAGE_CODE;
  if (code === DEFAULT_LANGUAGE_CODE) {
    return { ...(APP_SHELL_LOCALES.en || {}) };
  }
  const locale = APP_SHELL_LOCALES[code];
  return locale ? { ...locale } : {};
}

/**
 * @param {string | null | undefined} lang
 */
export function overlayAppShellLocaleForLanguage(lang) {
  overlayI18nStrings(getAppShellLocaleBundle(lang));
}
